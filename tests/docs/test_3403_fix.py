def _script_code() -> str:
    """The script with comments stripped and line continuations joined, so an
    assertion about an invocation cannot be satisfied by prose about it (the
    header deliberately names the old `curl -fsSL` to explain #3403)."""
    body = "\n".join(ln for ln in _script_text().splitlines() if not ln.lstrip().startswith("#"))
    return body.replace("\\\n", " ")


