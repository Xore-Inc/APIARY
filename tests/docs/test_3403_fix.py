def test_the_export_routes_own_contract_is_unchanged():
    """The sidecar's checks are derived from the route's generated contract,
    so that contract is load-bearing: 200 carries `text/plain` (which is why
    the content-type gate is written the way it is) and there is no 3xx (which
    is why redirects are not followed). #3403 changed the caller; it must not
    have changed the route, its status codes, or its behaviour.

    openapi.json is GENERATED by utoipa (#3382) -- regenerate with
    `cargo run --bin openapi`, never hand-edit. Reading it here is how a
    hand-edit that changed a status code would be caught."""
    spec = json.loads(OPENAPI_JSON.read_text(encoding="utf-8"))
    responses = spec["paths"][REAL_ROUTE]["get"]["responses"]
    assert set(responses) == {"200", "401", "502"}, (
        f"the export route's status codes changed; #3403 must not touch them. Got {sorted(responses)}"
    )
    assert "text/plain" in responses["200"]["content"], (
        "the export's 200 must stay text/plain -- the sidecar's content-type "
        f"gate is written against it. Got {sorted(responses['200']['content'])}"
    )
    assert not [code for code in responses if code.startswith("3")], (
        "the export route declares a 3xx; there is no legitimate redirect here, "
        "and the sidecar's do-not-follow decision is derived from that"
    )
    assert spec["paths"][REAL_ROUTE]["get"]["security"] == [{"serviceToken": []}], (
        "the export must stay service-token gated -- the sidecar authenticates "
        "because of this, and it is the reason an unauthenticated fetch 307s"
    )


