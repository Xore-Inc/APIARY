#!/usr/bin/env python3
"""Regression tests for #3403: the VPS IP-block sidecar fetched a URL that is
not a route, and could not tell it had failed.

`vps/portbridge-manual-blackhole-refresh.sh` defaulted
`MANUAL_BLACKHOLE_URL` to `/export/portbridge-manual-blackhole.txt`. Measured
live on the homeserver, that path answers 200 with a 0-byte body (an HTML
auth-redirect page), and the route that actually serves the export,
`/api/v1/ip-block-export`, answers 307 to `/auth/login?return_to=...` to an
unauthenticated caller. So `curl -fsSL` exited 0, the sidecar logged
"updated ... (0 addresses)", and every 300 seconds it replaced a working
`/blackhole/manual.txt` with nothing. Operator IP blocks never reached
portbridge and there was no signal anywhere that they had stopped.

The failure was silent for a specific, repeatable reason: the frontend answers
an *unknown path* with an auth redirect, so a 404-shaped mistake and a
200-shaped success were indistinguishable to `curl -f`. A missing route
returning 404 was always handled; the 200-with-0-bytes and the 307-to-login
were not, and those are the two the tests below drive.

What these tests pin:

* a 200 with a 0-byte body is refused, and the existing list survives
  byte-for-byte;
* a 307 to the login page is refused, and the existing list survives
  byte-for-byte (a redirect HTML page is not a blocklist -- that is the bug);
* a 404 is still refused the same way, so the one case that already worked
  keeps working;
* a real export is written, and the address count in the log matches the file;
* the request authenticates with the dashboard's existing service token, in
  the existing `X-Service-Token` header, handed to curl through its stdin
  config so the secret is never in argv, the process list, or the log -- and
  an unset token is a loud refusal rather than an unauthenticated attempt,
  because the unauthenticated answer IS the bug;
* nothing here is allowed to change the route: `openapi.json` is generated by
  utoipa and the export's contract (200 `text/plain`, 401, 502) is what the
  sidecar's checks are derived from. Notably the contract has no 3xx at all,
  which is why the sidecar does not follow redirects -- a 307 on the wire is
  an interception, never this route.

The behavioural half runs the real script against a real local HTTP server
with real curl, the same shape test_3283_fix.py established: the failure here
is a specific HTTP response body, and a stubbed `curl` cannot produce one.
"""
