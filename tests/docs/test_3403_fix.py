# ------------------------------------------------- the response the test serves ----

# A real blocklist body must be accepted; anything else is what the sidecar
# is supposed to refuse. Enforced rather than documented: a mode string that
# does not match would fall through the handler to the "real export" branch,
# and every negative test below would then pass vacuously against a working
# sidecar.
MODES = ("export", "empty-200", "redirect-307", "html-200", "not-found-404", "unauthorized-401", "server-error-503")


class _ExportHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):  # silence the default stderr spam
        pass

    def _respond(self, status: int, body: bytes, content_type: str, extra=()):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for key, value in extra:
            self.send_header(key, value)
        self.end_headers()
        if body:
            self.wfile.write(body)

    def do_GET(self):  # noqa: N802 -- http.server's own name
        server = self.server
        server.requests.append(
            {
                "path": self.path,
                "token": self.headers.get("X-Export-Token"),
                "service_token": self.headers.get("X-Service-Token"),
            }
        )
        mode = server.mode
        if self.path.startswith("/auth/login"):
            self._respond(200, LOGIN_PAGE, "text/html; charset=utf-8")
        elif mode == "empty-200":
            # The measured #3403 shape: a success status, no body at all.
            self._respond(200, b"", "text/plain; charset=utf-8")
        elif mode == "redirect-307":
            self._respond(
                307,
                b"",
                "text/plain; charset=utf-8",
                extra=[("Location", "/auth/login?return_to=" + self.path)],
            )
        elif mode == "html-200":
            # A login page delivered as a plain 200 -- what a redirect-following
            # fetch ends up holding. The status gate cannot catch it; the
            # content-type and line-format gates exist for exactly this.
            self._respond(200, LOGIN_PAGE, "text/html; charset=utf-8")
        elif mode == "unauthorized-401":
            # What the dashboard answers a wrong, missing or SERVICE_TOKEN
            # credential on the export route.
            self._respond(401, b"unauthorized", "text/plain; charset=utf-8")
        elif mode == "server-error-503":
            self._respond(503, b"unavailable", "text/plain; charset=utf-8")
        elif mode == "not-found-404":
            self._respond(404, b"not found", "text/plain; charset=utf-8")
        else:
            self._respond(200, server.export_body, "text/plain; charset=utf-8")


class _Server(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, mode: str):
        super().__init__(("127.0.0.1", 0), _ExportHandler)
        self.mode = mode
        self.export_body = A_REAL_EXPORT.encode()
        self.requests: list[dict] = []


@pytest.fixture
def export_server():
    """Yields a factory: `export_server("empty-200")` starts a server in that
    mode and tears it down afterwards. One server per test keeps the request
    log unambiguous about which case saw what."""
    servers = []

    def start(mode: str) -> _Server:
        assert mode in MODES, f"unknown response mode {mode!r}; a typo would fall through to a valid export"
        server = _Server(mode)
        threading.Thread(target=server.serve_forever, daemon=True).start()
        servers.append(server)
        return server

    yield start
    for server in servers:
        server.shutdown()
        server.server_close()


# ------------------------------------------------------ driving the real script ----

# The loop only ever reaches `updated ...` or a `[E-*]` refusal after it has
# decided what to do with the response, so this is the point at which the
# filesystem and the log both describe the same, settled, decision.
SETTLED = re.compile(r"portbridge-manual-blackhole-refresh: (updated |\[E-)")


def _run_sidecar(
    tmp_path: pathlib.Path,
    port: int,
    token: str | None,
    settle_timeout: float = 25.0,
    extra_env: dict | None = None,
):
    """Run the real script once against the local server and return
    (stderr, list contents, stray files in the list's directory).

    The script is a `while true` 5-minute loop, so the interval is set far
    past the test's patience and the process is stopped the moment the first
    iteration has made and announced its decision. That is the only race-free
    moment to inspect: before it, nothing has happened; after it, the next
    iteration is 3600s away."""
    blackhole = tmp_path / "blackhole"
    blackhole.mkdir(exist_ok=True)
    dest = blackhole / "manual.txt"
    dest.write_text(WORKING_LIST)

    env = dict(os.environ)
    env["MANUAL_BLACKHOLE_URL"] = f"http://127.0.0.1:{port}{EXPORT_ROUTE}"
    env.pop(SERVICE_TOKEN_ENV, None)
    env.update(extra_env or {})
    env["BLACKHOLE_MANUAL_LIST"] = str(dest)
    env["MANUAL_REFRESH_INTERVAL_SECONDS"] = "3600"
    if token is None:
        env.pop(TOKEN_ENV, None)
    else:
        env[TOKEN_ENV] = token

    proc = subprocess.Popen(
        ["sh", str(SCRIPT)],
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        lines: list[str] = []
        deadline = threading.Event()

        def drain():
            for line in proc.stderr:
                lines.append(line)
                if SETTLED.search(line):
                    deadline.set()

        reader = threading.Thread(target=drain, daemon=True)
        reader.start()
        assert deadline.wait(settle_timeout), (
            "the sidecar never announced a decision within "
            f"{settle_timeout}s; stderr so far: {''.join(lines)!r}"
        )
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:  # pragma: no cover -- only on a wedged sh
            proc.kill()
            proc.wait(timeout=10)
        reader.join(timeout=10)

    stderr = "".join(lines)
    stray = sorted(p.name for p in blackhole.iterdir() if p.name != "manual.txt")
    return stderr, dest.read_text(), stray


